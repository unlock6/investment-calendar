/**
 * 메시지에 대한 로컬 폴백 응답 생성
 */
export function getLocalFallbackResponse(message) {
  const lowerMsg = message.toLowerCase();

  // 패턴 매칭으로 적절한 카테고리 찾기
  for (const [, category] of Object.entries(FALLBACK_RESPONSES)) {
    if (category.patterns) {
      const matched = category.patterns.some(p => lowerMsg.includes(p));
      if (matched) {
        const responses = category.responses;
        return responses[Math.floor(Math.random() * responses.length)];
      }
    }
  }

  // 기본 폴백
  const defaults = FALLBACK_RESPONSES.default.responses;
  return defaults[Math.floor(Math.random() * defaults.length)];
}

